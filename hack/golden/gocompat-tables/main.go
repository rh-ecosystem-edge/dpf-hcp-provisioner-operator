// Command gocompat-tables generates crates/gocompat/src/unicode_tables.rs from the
// Unicode tables of the Go toolchain in use, so that the Rust port classifies runes
// exactly like Go's unicode / strconv packages do.
//
// Run from the repository root: go run -mod=vendor ./hack/golden/gocompat-tables
package main

import (
	"bytes"
	"fmt"
	"os"
	"runtime"
	"strconv"
	"unicode"
)

type class struct {
	name string
	doc  string
	fn   func(r rune) bool
}

func main() {
	classes := []class{
		{"IS_PRINT", "strconv.IsPrint / unicode.IsPrint", strconv.IsPrint},
		{"IS_LETTER", "unicode.IsLetter", unicode.IsLetter},
		{"IS_DIGIT", "unicode.IsDigit", unicode.IsDigit},
		{"IS_SPACE", "unicode.IsSpace", unicode.IsSpace},
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by hack/golden/gocompat-tables (%s, Unicode %s); DO NOT EDIT.\n\n", runtime.Version(), unicode.Version)
	for _, c := range classes {
		var ranges [][2]rune
		inRange := false
		var start rune
		for r := rune(0); r <= unicode.MaxRune+1; r++ {
			in := r <= unicode.MaxRune && c.fn(r)
			if in && !inRange {
				start = r
				inRange = true
			} else if !in && inRange {
				ranges = append(ranges, [2]rune{start, r - 1})
				inRange = false
			}
		}
		fmt.Fprintf(&out, "/// Inclusive rune ranges for which Go's `%s` reports true.\n", c.doc)
		fmt.Fprintf(&out, "pub(crate) static %s: &[(u32, u32)] = &[\n", c.name)
		for i, rg := range ranges {
			if i%4 == 0 {
				out.WriteString("   ")
			}
			fmt.Fprintf(&out, " (0x%X, 0x%X),", rg[0], rg[1])
			if i%4 == 3 || i == len(ranges)-1 {
				out.WriteString("\n")
			}
		}
		out.WriteString("];\n\n")
	}
	b := bytes.TrimRight(out.Bytes(), "\n")
	b = append(b, '\n')
	if err := os.WriteFile("crates/gocompat/src/unicode_tables.rs", b, 0o644); err != nil {
		panic(err)
	}
}
